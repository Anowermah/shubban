    /**
     * Seed default knowledge items if empty.
     */
    public static function seedDefaultsIfEmpty(): void
    {
        if (self::count() === 0) {
            foreach (self::defaultKnowledgeItems() as $item) {
                self::create($item);
            }
        }
    }

    /**
     * Restore/Reset knowledge base to factory default items.
     */
    public static function resetToDefaults(): void
    {
        self::truncate();
        foreach (self::defaultKnowledgeItems() as $item) {
            self::create($item);
        }
    }
